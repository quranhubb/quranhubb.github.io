const DICTS: Record<Locale, Dict> = { en, ur, ar };

export function translate(locale: Locale, key: keyof typeof en | string): string {
  return DICTS[locale]?.[key] ?? en[key] ?? String(key);
}

export const isRtl = (locale: Locale) => locale === "ur" || locale === "ar";
